import AppKit

/// Text copied while dictating, to go into the text at the point it was copied. Everything before typing
/// (the transcript, the cleanup model, the pill) only sees its placeholder, so the content goes in untouched
/// and however long it is, it costs the cleanup nothing
struct Clip {
    let text: String
    let number: Int

    var isLink: Bool {
        guard !text.contains(where: \.isWhitespace), let url = URL(string: text), url.host != nil else { return false }
        return ["http", "https"].contains(url.scheme?.lowercased() ?? "")
    }

    /// What stands in for it until it's typed. The kind tells the cleanup model what "这个链接" refers to
    var token: String { "⟦\(isLink ? "链接" : "文字")\(number)⟧" }

    /// How the pill shows it: the site for a link, the first few characters otherwise
    var label: String {
        if isLink, let host = URL(string: text)?.host {
            return "🔗 " + (host.hasPrefix("www.") ? String(host.dropFirst(4)) : host)
        }
        let line = text.replacingOccurrences(of: "\n", with: " ")
        return "📋 " + (line.count > 10 ? String(line.prefix(10)) + "…" : line)
    }

    /// Its content where its placeholder was: on lines of its own if it has several, and a link with a space
    /// after, or an app making it clickable takes in the next character too
    func placed(after prev: Character?, before next: Character?) -> String {
        if text.contains(where: \.isNewline) {
            return ((prev?.isNewline ?? true) ? "" : "\n") + text + ((next?.isNewline ?? true) ? "" : "\n")
        }
        return isLink && next.map({ !$0.isWhitespace }) == true ? text + " " : text
    }

    /// `text` with each clip's content where its placeholder is
    static func fill(_ text: String, with clips: [Clip]) -> String {
        var out = text
        for clip in clips {
            guard let r = out.range(of: clip.token) else { continue }
            let content = clip.placed(after: out[..<r.lowerBound].last, before: out[r.upperBound...].first)
            out.replaceSubrange(r, with: content)
        }
        return out
    }

    /// `text` as the pill shows it: each placeholder as its clip's label
    static func labeled(_ text: String, with clips: [Clip]) -> String {
        clips.reduce(text) { $0.replacingOccurrences(of: $1.token, with: " \($1.label) ") }
    }

    /// Puts placeholders into a sentence, each `offset` characters in: as much of the sentence as had been
    /// heard when it was copied
    static func insert(_ marks: [(token: String, offset: Int)], into sentence: String) -> String {
        var out = sentence
        for m in marks.reversed() {
            out.insert(contentsOf: m.token, at: out.index(out.startIndex, offsetBy: min(m.offset, out.count)))
        }
        return out
    }
}

/// Notices text copied while dictating. The pasteboard posts no notification, so its change count is polled
final class ClipboardWatch {
    private var timer: Timer?
    private var count = 0
    /// Password managers and clipboard tools mark what they put there (nspasteboard.org): never type that
    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    func start(onCopy: @escaping (String) -> Void) {
        stop()
        let pb = NSPasteboard.general
        count = pb.changeCount
        let t = Timer(timeInterval: 0.2, repeats: true) { [weak self] _ in
            guard let self, pb.changeCount != self.count else { return }
            self.count = pb.changeCount
            if pb.types?.contains(where: { Self.skipped.contains($0.rawValue) }) == true {
                Log.write("Clip: skipped a copy marked concealed or transient")
                return
            }
            guard let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
                  !text.isEmpty else { return }
            onCopy(text)
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }
}
